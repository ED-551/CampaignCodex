/**
 * Email utility — sends through Resend, SMTP, or stubs to the console.
 *
 * The provider is picked once at startup (see config/email.js): Resend when
 * RESEND_API_KEY is set, else SMTP when SMTP_HOST is set, else the console stub.
 *
 * All functions follow the same stub pattern: with no provider configured
 * (local dev / CI / a self-hosted instance without mail), they print the email
 * content to stdout and return early. This means the full email flow can be
 * exercised locally without real credentials or network access.
 */

const nodemailer = require('nodemailer')
const { EMAIL_MODE, RESEND_API_KEY: API_KEY, SMTP } = require('../config/email')

const FROM    = process.env.EMAIL_FROM   || 'noreply@campaigncodex.com'
const CLIENT  = process.env.CLIENT_URL   || 'http://localhost:5173'
const STUB    = EMAIL_MODE === 'console'

// Pause between messages when a newsletter goes out over SMTP, so a small
// mail server or a relay with per-second limits isn't flooded.
const SMTP_BROADCAST_DELAY_MS = 250

// Created on first use so a misconfigured SMTP server never blocks startup.
let smtpTransport = null
function getSmtpTransport() {
  if (!smtpTransport) {
    smtpTransport = nodemailer.createTransport({
      host:   SMTP.host,
      port:   SMTP.port,
      secure: SMTP.secure,
      auth:   SMTP.user ? { user: SMTP.user, pass: SMTP.pass } : undefined,
      // Fail fast: signup waits on the verification email.
      connectionTimeout: 15_000,
      greetingTimeout:   15_000,
      socketTimeout:     30_000,
    })
  }
  return smtpTransport
}

/**
 * Send one message through the configured provider (Resend or SMTP).
 * Throws on delivery failure. Callers handle the console stub themselves.
 */
async function deliver(toEmail, subject, html) {
  if (EMAIL_MODE === 'smtp') {
    try {
      await getSmtpTransport().sendMail({
        from: `CampaignCodex <${FROM}>`,
        to:   toEmail,
        subject,
        html,
      })
    } catch (err) {
      // Re-throw a plain Error with only the message so nothing from the
      // transport (connection details, auth state) ends up in the logs.
      throw new Error(`SMTP error: ${err.message}`)
    }
    return
  }

  // Live: Resend API
  const res = await fetch('https://api.resend.com/emails', {
    method:  'POST',
    headers: {
      'Authorization': `Bearer ${API_KEY}`,
      'Content-Type':  'application/json',
    },
    body: JSON.stringify({
      from:    `CampaignCodex <${FROM}>`,
      to:      [toEmail],
      subject,
      html,
    }),
  })

  if (!res.ok) {
    const err = await res.json().catch(() => ({}))
    throw new Error(`Resend error: ${JSON.stringify(err)}`)
  }
}

// Shared HTML shell for all outbound emails.
// footer: optional override — defaults to the transactional account notice.
//         Pass NEWSLETTER_FOOTER for opt-in broadcast emails.
const NEWSLETTER_FOOTER =
  "You're receiving this because you opted in to the CampaignCodex newsletter.<br>" +
  'To unsubscribe, sign in and update your notification preferences in account settings.'

// Two distinct footer strings matter for CAN-SPAM / GDPR compliance:
// transactional messages (password reset, username reminder) don't require an
// unsubscribe link, but broadcast/newsletter messages do.
const TRANSACTIONAL_FOOTER =
  "You're receiving this email because it was requested for your CampaignCodex account.<br>" +
  'If you did not make this request, you can safely ignore it.'

/**
 * Wrap an HTML content block in the shared CampaignCodex email shell.
 * Keeps all emails visually consistent without duplicating the header/footer
 * markup in every send function.
 *
 * @param {string} inner  - The body HTML to inject between header and footer.
 * @param {string} [footer=TRANSACTIONAL_FOOTER] - Footer copy. Pass
 *   NEWSLETTER_FOOTER for broadcast emails so they include an unsubscribe note.
 * @returns {string} Complete HTML email string ready to send.
 */
function wrapHtml(inner, footer = TRANSACTIONAL_FOOTER) {
  return `
    <div style="font-family:sans-serif;max-width:600px;margin:0 auto;
                background:#0f1117;color:#e2e8f0;padding:32px 24px;border-radius:12px">
      <div style="border-bottom:1px solid #2d3748;padding-bottom:16px;margin-bottom:24px">
        <h1 style="color:#c9a84c;font-size:20px;margin:0;font-weight:700;letter-spacing:0.05em">
          CampaignCodex
        </h1>
      </div>
      <div style="line-height:1.7;color:#e2e8f0;font-size:15px">
        ${inner}
      </div>
      <div style="border-top:1px solid #2d3748;padding-top:16px;margin-top:32px;
                  font-size:12px;color:#6b7280;line-height:1.5">
        ${footer}
      </div>
    </div>
  `
}

/**
 * Send a password-reset email containing a one-time link.
 * The link encodes a short-lived token generated by the auth route;
 * expiry enforcement happens on the backend when the token is redeemed,
 * not here.
 *
 * @param {string} toEmail    - Recipient's email address.
 * @param {string} resetToken - Opaque token to embed in the reset URL.
 * @returns {Promise<{ok:boolean, stub?:boolean}>}
 */
async function sendPasswordResetEmail(toEmail, resetToken) {
  const link = `${CLIENT}/reset-password?token=${resetToken}`

  if (STUB) {
    // Stub: log to console for homelab dev
    console.log('\n─── PASSWORD RESET EMAIL (stub) ───────────────────')
    console.log(`To:      ${toEmail}`)
    console.log(`Link:    ${link}`)
    console.log('────────────────────────────────────────────────────\n')
    return { ok: true, stub: true }
  }

  const html = wrapHtml(`
    <p>A password reset was requested for your account.</p>
    <p>
      <a href="${link}"
         style="display:inline-block;background:#c9a84c;color:#0a0b0f;
                padding:12px 24px;border-radius:8px;font-weight:600;
                text-decoration:none">
        Reset Password
      </a>
    </p>
    <p style="font-size:13px;color:#6b7280">
      This link expires in 1 hour. If you didn't request this, you can safely ignore this email.
    </p>
  `)

  await deliver(toEmail, 'Reset your CampaignCodex password', html)

  return { ok: true }
}

/**
 * Send a broadcast email to a list of opted-in newsletter subscribers.
 * Resend: uses the batch API (up to 100 per request) for efficiency.
 * SMTP: one message per recipient, with a short pause between them, so no
 * message ever lists more than one subscriber.
 * Falls back to console stub when no email provider is configured.
 *
 * @param {Array<{email:string, username:string}>} recipients
 * @param {string} subject
 * @param {string} plainBody — Admin's plain-text message (newlines → <p> tags)
 * @returns {Promise<{sent:number, failed:number, stub:boolean}>}
 */
async function sendBroadcastEmail(recipients, subject, plainBody) {
  // Escape HTML entities and convert newlines to paragraphs
  const escaped = plainBody
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')

  const htmlBody = escaped
    .split('\n')
    .map(line => line.trim()
      ? `<p style="margin:0 0 14px">${line}</p>`
      : '<p style="margin:0 0 14px">&nbsp;</p>')
    .join('\n')

  const html = wrapHtml(htmlBody, NEWSLETTER_FOOTER)

  if (STUB) {
    console.log('\n─── BROADCAST EMAIL (stub) ─────────────────────────')
    console.log(`Subject:    ${subject}`)
    console.log(`Recipients: ${recipients.length}`)
    recipients.slice(0, 5).forEach(r => console.log(`  → ${r.email} (${r.username})`))
    if (recipients.length > 5) console.log(`  … and ${recipients.length - 5} more`)
    console.log('────────────────────────────────────────────────────\n')
    return { sent: recipients.length, failed: 0, stub: true }
  }

  if (EMAIL_MODE === 'smtp') {
    let sent   = 0
    let failed = 0
    for (let i = 0; i < recipients.length; i++) {
      if (i > 0) await new Promise(r => setTimeout(r, SMTP_BROADCAST_DELAY_MS))
      try {
        await deliver(recipients[i].email, subject, html)
        sent++
      } catch (err) {
        console.error(`[broadcast] ${err.message} (recipient ${i + 1} of ${recipients.length})`)
        failed++
      }
    }
    return { sent, failed, stub: false }
  }

  // Chunk into groups of 100 (Resend batch API limit)
  const CHUNK_SIZE = 100
  let sent   = 0
  let failed = 0

  for (let i = 0; i < recipients.length; i += CHUNK_SIZE) {
    const chunk = recipients.slice(i, i + CHUNK_SIZE)
    const batch = chunk.map(r => ({
      from:    `CampaignCodex <${FROM}>`,
      to:      [r.email],
      subject,
      html,
    }))

    try {
      const res = await fetch('https://api.resend.com/emails/batch', {
        method:  'POST',
        headers: {
          'Authorization': `Bearer ${API_KEY}`,
          'Content-Type':  'application/json',
        },
        body: JSON.stringify(batch),
      })

      if (!res.ok) {
        const err = await res.json().catch(() => ({}))
        console.error('[broadcast] Resend batch error:', err)
        failed += chunk.length
      } else {
        sent += chunk.length
      }
    } catch (err) {
      console.error('[broadcast] Network error on batch:', err.message)
      failed += chunk.length
    }
  }

  return { sent, failed, stub: false }
}

/**
 * Send a username reminder to a user who has forgotten their username.
 * Triggered by entering the registered email on the forgot-username flow.
 *
 * @param {string} toEmail
 * @param {string} username
 */
